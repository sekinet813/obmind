  static const body = '''
Obmindは、アカウントも独自のサーバーも持たない、Local-firstなマインドマップアプリです。思考はMarkdownファイルとして、あなたが選んだフォルダに残ります。

収集しないデータ

Obmindは、氏名、メールアドレス、位置情報、連絡先、広告IDなどの個人情報を集めません。利用状況の解析や広告のための送信もしません。アカウント登録は不要です。

ファイルの扱い

マインドマップの内容は、端末と、あなたが選んだ保存フォルダに留まります。Obmindが選んだフォルダのMarkdownを読み書きするのは、地図を表示・編集・保存するためです。選んでいないフォルダへはアクセスしません。

保存フォルダの場所、最近開いた地図、一覧の表示方法など、アプリの操作に必要な設定は端末内にだけ覚えます。これらの設定をObmindのサーバーへ送ることはありません。独自サーバー自体がありません。

第三者への送信

思考の内容も、端末内の設定も、第三者へ送信しません。クラウドへ自動でアップロードする機能はありません。別アプリやクラウドへ置くかどうかは、あなたが選んだフォルダの置き場所に従います。

アプリを削除した場合

Obmindをアンインストールしても、あなたが選んだフォルダにあるMarkdownファイルは、その場所に残ります。端末内のアプリ設定だけが消えます。
''';
